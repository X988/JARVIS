import type { AgentTurnResult } from "../plane/agent-runtime.ts";
import { callJsonModel, type FetchLike } from "../plane/llm-client.ts";

/** Hard cap for what Piper reads aloud; the full report stays on screen. */
export const SPOKEN_MAX_CHARS = 400;

const CHECK_NAMES: Record<string, string> = {
  "mikrotik.status": "состояние роутера",
  "mikrotik.resources": "загрузка роутера",
  "mikrotik.interfaces": "интерфейсы",
  "mikrotik.routes": "маршруты",
  "mikrotik.dhcp": "DHCP",
  "mikrotik.firewall.counters": "файрвол",
  "mikrotik.logs": "журнал роутера",
  "mikrotik.wireguard": "WireGuard",
  "wireguard.status": "WireGuard",
  "mikrotik.wan.status": "WAN",
};

/**
 * Removes everything a speech engine should not read: markdown, code, hashes,
 * MACs, UUIDs, paths, URLs, key=value dumps, runbook ids, list numbering.
 * Then caps the text at a sentence boundary.
 */
export function sanitizeSpeakable(text: string, max = SPOKEN_MAX_CHARS): string {
  let out = String(text ?? "");
  out = out
    .replace(/\s*Источник(?:и)?:[^\n]*$/gim, "")
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`[^`]*`/g, " ")
    .replace(/https?:\/\/\S+/gi, " ")
    .replace(/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/gi, " ")
    .replace(/\b(?:[0-9a-f]{2}[:-]){5}[0-9a-f]{2}\b/gi, " ")
    .replace(/\b[0-9a-f]{16,}\b/gi, " ")
    .replace(/(^|\s)(?:~|\.{1,2})?\/[\w.\-/]+/g, " ")
    .replace(/\b[a-z][\w-]*(?:\.[\w-]+)+@[^\s:;,]+:?/gi, " ")
    .replace(/\b[a-z_][\w-]*:[a-z_][\w-]*:/gi, " ")
    .replace(/\b[\w.-]+=[^\s;,]*/g, " ")
    .replace(/\[[^\]]{0,40}\]/g, " ")
    .replace(/^\s*(?:\d+\.|[-*•#>]+)\s*/gm, "")
    .replace(/[*_#|<>{}\\[\]→]/g, " ")
    .replace(/\s*;\s*/g, ", ")
    .replace(/\s+([,.!?])/g, "$1")
    .replace(/([,.!?])(?:\s*[,.]){1,}/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
  if (out.length <= max) return out;
  const cut = out.slice(0, max);
  const end = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("! "), cut.lastIndexOf("? "));
  return (end > max * 0.4 ? cut.slice(0, end + 1) : cut.replace(/[\s,]+\S*$/, "") + "…").trim();
}

type Fact = { check: string; ok: boolean; status: string; facts: string };

function factsOf(result: AgentTurnResult): Fact[] {
  return (result.observations ?? []).map((item) => ({
    check: CHECK_NAMES[item.tool] ?? item.tool.replace(/[._]/g, " "),
    ok: item.code === "OK" || item.code === "MOCK",
    status: item.code,
    facts: item.detail
      .replace(/\b(?:[0-9a-f]{2}[:-]){5}[0-9a-f]{2}\b/gi, "<mac>")
      .replace(/\b[0-9a-f]{16,}\b/gi, "")
      .replace(/^[\w-]+:[\w-]+:\s*/, "")
      .slice(0, 400),
  }));
}

function kv(detail: string, key: string): string | null {
  const m = new RegExp(`(?:^|[;\\s])${key}=([^;]+)`).exec(detail);
  return m ? m[1].trim() : null;
}

/** Rule-based short summary; used when the model is unavailable or returns junk. */
export function detectedProblems(result: AgentTurnResult): string[] {
  const obs = result.observations ?? [];
  const problems: string[] = [];
  for (const o of obs) {
    const down = kv(o.detail, "down");
    if (down && down !== "none") problems.push(`не подняты интерфейсы ${down.split(",").slice(0, 4).join(", ")}`);
    const errors = Number(kv(o.detail, "errors") ?? 0);
    if (errors > 0) problems.push(`в журнале ${errors} ошибок`);
    const defActive = kv(o.detail, "default_active");
    if (defActive === "0") problems.push("нет активного маршрута по умолчанию");
  }
  return problems;
}

export function fallbackSpoken(result: AgentTurnResult): string {
  const obs = result.observations ?? [];
  if (obs.length === 0) return sanitizeSpeakable(result.answer || "Ответа нет.");
  const failed = obs.filter((o) => !(o.code === "OK" || o.code === "MOCK"));
  const problems = detectedProblems(result);
  const verdict = problems.length
    ? `Проверка выполнена. Обратите внимание: ${problems.join("; ")}.`
    : failed.length === obs.length
      ? "Проверка не удалась: ни одна проверка не вернула данные."
      : "Проверка выполнена, явных проблем не видно.";
  const extra = failed.length && failed.length < obs.length ? ` ${failed.length} проверки не выполнены.` : "";
  return sanitizeSpeakable(`${verdict}${extra} Подробный отчёт на экране.`);
}

const SPOKEN_SCHEMA = {
  type: "object",
  additionalProperties: false,
  required: ["spoken"],
  properties: { spoken: { type: "string", maxLength: 600 } },
};

/**
 * Short spoken summary of an agent turn: 2–3 Russian sentences (verdict, main
 * problem, what to do), generated by the model from structured facts only.
 * The result is always sanitized and capped; on any model failure a rule-based
 * summary is used.
 */
export async function spokenSummary(
  result: AgentTurnResult,
  opts: { env?: NodeJS.ProcessEnv; fetch?: FetchLike; request?: string } = {},
): Promise<string> {
  const obs = result.observations ?? [];
  if (obs.length === 0) {
    const plain = sanitizeSpeakable(result.answer || "");
    return plain || "Ответа нет.";
  }
  try {
    const reply = await callJsonModel(
      "intent",
      {
        system: [
          "Ты JARVIS, голосовой помощник администратора. Ответ будет прочитан вслух синтезатором речи.",
          "Сформулируй по-русски 2–3 коротких предложения, не длиннее 350 символов: общий вывод, главная проблема (если есть), что делать.",
          "Используй только переданные факты. Не придумывай. Обязательно назови проблемы из detected_problems (например, какие интерфейсы не подняты). Не перечисляй сырые строки журнала.",
          "Запрещено: markdown, списки, MAC-адреса, хеши, идентификаторы, пути к файлам, имена инструментов, записи вида key=value, английские технические ключи.",
          "Числа пиши словами или цифрами, единицы по-русски (процентов, мегабайт). Неуспешные проверки упомяни одной фразой без технических кодов.",
          "Закончи фразой, что подробный отчёт на экране.",
        ].join("\n"),
        user: JSON.stringify({ request: opts.request ?? "", outcome: result.code, detected_problems: detectedProblems(result), checks: factsOf(result) }),
        schema: SPOKEN_SCHEMA,
      },
      { env: opts.env, fetch: opts.fetch },
    );
    if (reply.ok) {
      const raw = (reply.value as { spoken?: unknown })?.spoken;
      const clean = typeof raw === "string" ? sanitizeSpeakable(raw) : "";
      if (clean.length >= 20 && /[а-яё]/i.test(clean)) return clean;
    }
  } catch {
    // fall through to the rule-based summary
  }
  return fallbackSpoken(result);
}
